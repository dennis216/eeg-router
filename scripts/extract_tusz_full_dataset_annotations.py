"""Extract all TUSZ v2.0.6 seizure annotations using only the CSV metadata.

This helper is run inside WSL because the dataset is stored under /mnt/d.
It reads every ``.csv_bi`` sidecar, takes the file duration from its header,
and emits a compact CSV suitable for the Windows-side summary/plot script.
"""

from __future__ import annotations

import csv
import glob
import os
from pathlib import Path


DATA_ROOT = Path("/mnt/d/TUH_EEG/TUSZ_v2.0.6/edf")
OUT = Path(
    "/mnt/c/Users/User/Documents/Codex/2026-08-03/du-q/reports/"
    "dataset_seizure_duration_distribution_v1/tusz_full_dataset_annotation_rows.csv"
)


def parse_duration(lines: list[str]) -> float:
    for line in lines:
        if line.startswith("# duration") and "=" in line:
            return float(line.split("=", 1)[1].strip().split()[0])
    raise ValueError("missing duration header")


def main() -> None:
    files = sorted(glob.glob(str(DATA_ROOT / "**" / "*.csv_bi"), recursive=True))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, object]] = []
    for sidecar in files:
        path = Path(sidecar)
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        duration = parse_duration(lines)
        rel = path.relative_to(DATA_ROOT)
        parts = rel.parts
        split = parts[0] if parts else "unknown"
        # .../patient/session/montage/file.csv_bi
        patient_id = parts[1] if len(parts) > 1 else "unknown"
        edf_name = path.name.removesuffix(".csv_bi")
        for line in lines:
            if not line or line.startswith("#") or line.startswith("channel,"):
                continue
            fields = line.split(",")
            if len(fields) < 4:
                continue
            label = fields[3].strip().lower()
            if label != "seiz":
                continue
            start = float(fields[1])
            end = float(fields[2])
            if end <= start:
                continue
            rows.append(
                {
                    "split": split,
                    "patient_id": patient_id,
                    "recording_id": str(rel.with_suffix("")),
                    "edf_name": edf_name,
                    "duration_s": duration,
                    "start_s": start,
                    "end_s": end,
                    "seizure_duration_s": end - start,
                }
            )
    # Add one metadata row per record implicitly through the distinct recording
    # keys in the output. A separate summary is generated by the main script.
    fields = [
        "split",
        "patient_id",
        "recording_id",
        "edf_name",
        "duration_s",
        "start_s",
        "end_s",
        "seizure_duration_s",
    ]
    with OUT.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    # A lightweight file-level index allows the total duration to include
    # background-only records without opening EDF files.
    index_path = OUT.with_name("tusz_full_dataset_record_index.csv")
    with index_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["split", "patient_id", "recording_id", "duration_s"])
        for sidecar in files:
            path = Path(sidecar)
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
            duration = parse_duration(lines)
            rel = path.relative_to(DATA_ROOT)
            writer.writerow([rel.parts[0], rel.parts[1], str(rel.with_suffix("")), duration])
    print(f"records={len(files)} seizure_rows={len(rows)} output={OUT}")


if __name__ == "__main__":
    main()
